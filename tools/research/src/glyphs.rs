//! The game menu's Chinese and Korean glyphs (`game/src/domain/glyphs_cjk.rs`), taken from
//! Fusion Pixel Font 8px (SIL Open Font License; its BDF files, monospaced, `zh_hans` and `ko`)
//! for exactly the characters the menu's Chinese and Korean texts use (`game/i18n/menu.txt`,
//! and the languages' names). Run again whenever those texts change:
//! `research glyphs ZH.bdf KO.bdf`.
use std::collections::{BTreeMap, BTreeSet};
use std::path::Path;

/// The game's menu catalogue and the file with the languages' names, from this tool's folder.
const MENU: &str = concat!(env!("CARGO_MANIFEST_DIR"), "/../../game/i18n/menu.txt");
const NAMES: &str = concat!(env!("CARGO_MANIFEST_DIR"), "/../../game/src/domain/i18n/mod.rs");
const OUT: &str = concat!(env!("CARGO_MANIFEST_DIR"), "/../../game/src/domain/glyphs_cjk.rs");

/// Chinese and Korean characters (and their punctuation), which the pixel font draws from the
/// table; the rest (Latin, Cyrillic, katakana) it has itself.
pub fn is_cjk(c: char) -> bool {
    matches!(c as u32, 0x2E80..=0x9FFF | 0xAC00..=0xD7AF | 0x1100..=0x11FF | 0xFF00..=0xFFEF) && !('\u{30A0}'..='\u{30FF}').contains(&c)
}

/// A BDF font's glyphs: code point -> its 8x8 cell, row by row (bit 7 the leftmost pixel).
fn read_bdf(path: &Path) -> BTreeMap<u32, [u8; 8]> {
    let text = std::fs::read_to_string(path).unwrap_or_else(|e| panic!("{}: {e}", path.display()));
    let ascent: i32 = text.lines().find_map(|l| l.strip_prefix("FONT_ASCENT ")).and_then(|v| v.trim().parse().ok()).unwrap_or(7);
    let mut out = BTreeMap::new();
    let mut lines = text.lines();
    while let Some(line) = lines.next() {
        if !line.starts_with("STARTCHAR") {
            continue;
        }
        let (mut code, mut bbx, mut rows) = (None, (0, 0, 0, 0), Vec::new());
        for l in lines.by_ref() {
            if let Some(v) = l.strip_prefix("ENCODING ") {
                code = v.trim().parse::<i64>().ok().filter(|&c| c >= 0).map(|c| c as u32);
            } else if let Some(v) = l.strip_prefix("BBX ") {
                let n: Vec<i32> = v.split_whitespace().filter_map(|x| x.parse().ok()).collect();
                bbx = (n[0], n[1], n[2], n[3]);
            } else if l == "BITMAP" {
                continue;
            } else if l == "ENDCHAR" {
                break;
            } else if let Ok(b) = u32::from_str_radix(l.trim(), 16) {
                // a row is as many hex bytes as the box is wide; keep its first byte
                let bytes = l.trim().len() / 2;
                rows.push((b >> (8 * (bytes - 1))) as u8);
            }
        }
        let Some(code) = code else { continue };
        let (_, h, xoff, yoff) = bbx;
        let top = ascent - (yoff + h);
        let mut cell = [0u8; 8];
        for (i, &r) in rows.iter().enumerate() {
            let y = top + i as i32;
            if (0..8).contains(&y) && xoff >= 0 {
                cell[y as usize] = r >> xoff;
            }
        }
        out.insert(code, cell);
    }
    out
}

/// Every Chinese or Korean character in the string literals of `file`, or (a catalogue) in
/// its lines.
fn characters_in(file: &str, into: &mut BTreeSet<char>) {
    let src = std::fs::read_to_string(file).unwrap_or_else(|e| panic!("{file}: {e}"));
    if file.ends_with(".txt") {
        into.extend(src.lines().filter(|l| !l.starts_with('#')).flat_map(|l| l.chars()).filter(|&c| is_cjk(c)));
        return;
    }
    for (i, part) in src.split('"').enumerate() {
        if i % 2 == 1 {
            into.extend(part.chars().filter(|&c| is_cjk(c)));
        }
    }
}

pub fn write(zh: &Path, ko: &Path) {
    let mut wanted = BTreeSet::new();
    for f in [MENU, NAMES] {
        characters_in(f, &mut wanted);
    }
    let (zh, ko) = (read_bdf(zh), read_bdf(ko));
    let mut rows = Vec::new();
    for &c in &wanted {
        let hangul = matches!(c as u32, 0xAC00..=0xD7AF | 0x1100..=0x11FF);
        let font = if hangul { &ko } else { &zh };
        let Some(cell) = font.get(&(c as u32)) else {
            println!("no glyph for {c} (U+{:04X})", c as u32);
            continue;
        };
        if cell[0] != 0 {
            println!("{c}: its top row is cut (the menu's glyphs are 7 rows high)");
        }
        let seven: Vec<String> = cell[1..].iter().map(|r| format!("0x{r:02X}")).collect();
        rows.push(format!("    ('{c}', [{}]),", seven.join(", ")));
    }
    let out = format!(
        "//! The Chinese and Korean characters the menu's texts use, 7 rows of 8 pixels each (bit 7 the\n\
         //! leftmost), sorted by character. Generated by `research glyphs` from Fusion Pixel Font 8px\n\
         //! (SIL Open Font License, `fonts/OFL-FusionPixelFont.txt`): do not edit by hand.\n\
         pub const GLYPHS: &[(char, [u8; 7])] = &[\n{}\n];\n",
        rows.join("\n")
    );
    std::fs::write(OUT, out).unwrap_or_else(|e| panic!("{OUT}: {e}"));
    println!("{} characters written to {OUT}", rows.len());
}
